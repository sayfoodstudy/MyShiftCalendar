    private static void add(String date, String name) {
        PUBLIC_HOLIDAYS.put(date, name);
    }

    public static boolean isWeekend(LocalDate date) {
        DayOfWeek day = date.getDayOfWeek();
        return day == DayOfWeek.SATURDAY || day == DayOfWeek.SUNDAY;
    }

    public static boolean isPublicHoliday(LocalDate date) {
        return PUBLIC_HOLIDAYS.containsKey(DateUtil.iso(date));
    }

    public static boolean isHoliday(LocalDate date) {
        return isWeekend(date) || isPublicHoliday(date);
    }

    public static String getPublicHolidayName(LocalDate date) {
        return PUBLIC_HOLIDAYS.get(DateUtil.iso(date));
    }

    public static String getHolidayLabel(LocalDate date) {
        String publicName = getPublicHolidayName(date);
        if (publicName != null) return publicName;
        if (date.getDayOfWeek() == DayOfWeek.SATURDAY) return "토요일";
        if (date.getDayOfWeek() == DayOfWeek.SUNDAY) return "일요일";
        return null;
    }

    public static List<String> getPublicHolidayLinesForYear(int year) {
        List<String> lines = new ArrayList<>();
        for (Map.Entry<String, String> entry : PUBLIC_HOLIDAYS.entrySet()) {
            if (entry.getKey().startsWith(String.valueOf(year) + "-")) {
                lines.add(entry.getKey() + "  " + entry.getValue());
            }
        }
        java.util.Collections.sort(lines);
        return lines;
    }

    public static String getDataRangeText() {
        return "2026년~2035년 한국 공휴일 내장";
    }
